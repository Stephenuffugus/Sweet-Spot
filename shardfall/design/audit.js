// Dumps the live design tables out of the game so the plan cites real numbers, not remembered
// ones. Runs on the same harness the test suites use.
const out=[];
const L=s=>out.push(s);
L('# SHARDFALL — current-state audit');
L('');
L('_Generated from the live tables in `index.html`. Do not hand-edit; regenerate._');
L('');
L('## Scale');
L('');
L('| | |');
L('|---|---|');
L(`| world | ${WORLD_W} x ${WORLD_H} tiles (${(WORLD_W*TILE/1000).toFixed(1)}k x ${(WORLD_H*TILE/1000).toFixed(1)}k px) |`);
L(`| tile | ${TILE}px, chunk ${CHUNK}x${CHUNK} |`);
L(`| surface | y=${SURFACE} |`);
L(`| gravity / move / jump | ${GRAV} / ${MOVE} / ${JUMPV} |`);
L(`| flight | thrust ${FLY_THRUST}, drain ${FLY_DRAIN}/s, regen ${FLY_REGEN}/s, cap ${FLY_VMAX} |`);
L(`| fall | safe below ${FALL_SAFE}px/s, ${FALL_DMG} hp per px/s over, capped 55% maxHP |`);
L(`| crit | ${CRIT_BASE*100}% base, ${CRIT_MULT}x, status at ${CRIT_ST}x on crit |`);
L(`| focus | max ${FOCUS_MAX}, ${FOCUS_HIT}/hit, ${FOCUS_KILL}/kill, ${FOCUS_REGEN}/s idle |`);
L(`| weight | grace ${WEIGHT_GRACE}s, +1 per ${WEIGHT_EVERY}s, max ${WEIGHT_MAX} |`);
L('');
L('## Biomes');
L('');
L('| biome | ends at (tiles) | depth (m) | ground | cave density | roster |');
L('|---|---|---|---|---|---|');
let prev=0;
for(const b of BIOMES){
  L(`| ${b[1]} | ${b[0]} | ${Math.max(0,prev-SURFACE)}–${Math.max(0,b[0]-SURFACE)} | ${b[2]} | ${b[3]} | ${b[4].join(', ')} |`);
  prev=b[0];
}
L('');
L('## Enemies');
L('');
L('| enemy | hp | dmg | spd | armor | size | ai | windup | active | atk cd | lunge | shoot | shards |');
L('|---|---|---|---|---|---|---|---|---|---|---|---|---|');
for(const k in ENEMIES){const e=ENEMIES[k];const a=e.atk||{};
  L(`| ${k}${e.boss?' **(boss)**':''} | ${e.hp} | ${e.dmg} | ${e.spd} | ${e.arm||0} | ${e.w}x${e.h} | ${e.ai} | ${a.wind||'—'} | ${a.act||'—'} | ${a.cd||'—'} | ${a.lunge||'—'} | ${e.shoot?`cd ${e.shoot.cd} dmg ${e.shoot.dmg} x${e.shoot.count||1} r${e.shoot.range}`:'—'} | ${e.shards} |`);
}
L('');
L('### Depth scaling');
L('');
L('| depth (m) | depthMul | crawler hp | crawler dmg | brute hp | voidmaw hp |');
L('|---|---|---|---|---|---|');
for(const d of [0,200,400,900,1600,2400,3140]){
  const y=(SURFACE+d)*TILE,m=depthMul(y);
  L(`| ${d} | ${m.toFixed(2)}x | ${Math.round(ENEMIES.crawler.hp*m)} | ${Math.round(ENEMIES.crawler.dmg*m)} | ${Math.round(ENEMIES.brute.hp*m)} | ${Math.round(ENEMIES.voidmaw.hp*m)} |`);
}
L('');
L('## Gear bases');
L('');
L('| base | slot | dmg | cd | dps | range/speed | sockets | colors | armor | hp | fuel | dig |');
L('|---|---|---|---|---|---|---|---|---|---|---|---|');
for(const k in GEAR){const g=GEAR[k];
  const dps=g.dmg&&g.cd?(g.dmg/g.cd).toFixed(1):'—';
  L(`| ${g.n} | ${g.slot}${g.shield?' (shield)':''} | ${g.dmg||'—'} | ${g.cd||'—'} | ${dps} | ${g.range||g.speed||'—'} | ${g.sockets} | ${g.sc||'—'} | ${g.arm||0} | ${g.hp||0} | ${g.fuel||0} | ${g.dig!==undefined?g.dig:'—'} |`);
}
L('');
L('## Gems by type');
L('');
const byType={};
for(const k in GEMS){const g=GEMS[k];(byType[g.t]=byType[g.t]||[]).push([k,g])}
for(const t of ['skill','sup','aura','abil']){
  L(`### ${t} (${(byType[t]||[]).length})`);
  L('');
  L('| id | name | color | for | effect |');
  L('|---|---|---|---|---|');
  for(const [k,g] of (byType[t]||[])) L(`| ${k} | ${g.n} | ${g.col} | ${g.for} | ${(g.d||'').replace(/\|/g,'/')}${g.fc?` · ${g.cd}s / ${g.fc} focus`:''} |`);
  L('');
}
L('## Affixes');
L('');
L('| key | label | min | max | scale |');
L('|---|---|---|---|---|');
for(const a of AFFIXES) L(`| ${a[0]} | ${a[1]} | ${a[2]} | ${a[3]} | ${a[4]} |`);
L('');
L('## Uniques');
L('');
L('| base | primary | alternate |');
L('|---|---|---|');
for(const k in UNIQUES) L(`| ${k} | **${UNIQUES[k].n}** — ${UNIQUES[k].d} | ${UNIQ2[k]?`**${UNIQ2[k].n}** — ${UNIQ2[k].d}`:'—'} |`);
L('');
L('## Attunements (in-run levels)');
L('');
L('| id | name | effect | kind |');
L('|---|---|---|---|');
for(const a of ATTUNE) L(`| ${a.id} | ${a.n} | ${a.d} | ${a.fx?'stat':'mechanic'} |`);
L('');
L('### Level curve');
L('');
L('| level | xp to next | cumulative |');
L('|---|---|---|');
let cum=0;
for(let lv=1;lv<=14;lv++){const n=xpNeed(lv);cum+=n;L(`| ${lv} | ${n} | ${cum} |`)}
L('');
L('## Threat tiers');
L('');
L('| tier | requires | shards | rarity | effect |');
L('|---|---|---|---|---|');
THREATS.forEach((t,i)=>L(`| ${i} — ${t.n} | ${t.req} bosses | ${(t.shard*100).toFixed(0)}% | ${(t.rare*100).toFixed(0)}% | ${t.d} |`));
L('');
L('## Meta tree');
L('');
L('| id | branch | effect | cost | requires |');
L('|---|---|---|---|---|');
for(const n of TREE) L(`| ${n.id} | ${n.br} | ${n.n} | ${n.cost} | ${n.req||'—'} |`);
L('');
L('## Economy');
L('');
const unlockTotal=UNLOCKS.reduce((a,u)=>a+u.cost,0);
const treeTotal=TREE.reduce((a,n)=>a+n.cost,0);
const classTotal=Object.values(CLASSES).reduce((a,c)=>a+c.cost,0);
L('| sink | total shards |');
L('|---|---|');
L(`| unlock pool (${UNLOCKS.length} entries) | ${unlockTotal} |`);
L(`| meta tree (${TREE.length} nodes) | ${treeTotal} |`);
L(`| classes | ${classTotal} |`);
L(`| **total one-time** | **${unlockTotal+treeTotal+classTotal}** |`);
L(`| gem fusion | 150 (T1→T2) / 500 (T2→T3), unbounded |`);
L(`| vault deposit | ${VAULT_COST.join(' / ')} by rarity |`);
L('');
L('## Boons');
L('');
L('| name | effect |');
L('|---|---|');
for(const b of BOONS) L(`| ${b.n} | ${b.d} |`);
L('');
L('## Counts');
L('');
L('| | |');
L('|---|---|');
L(`| gems | ${Object.keys(GEMS).length} |`);
L(`| gear bases | ${Object.keys(GEAR).length} |`);
L(`| uniques | ${Object.keys(UNIQUES).length+Object.keys(UNIQ2).length} |`);
L(`| enemies | ${Object.keys(ENEMIES).length} |`);
L(`| affixes | ${AFFIXES.length} |`);
L(`| unlocks | ${UNLOCKS.length} |`);
L(`| tree nodes | ${TREE.length} |`);
L(`| boons | ${BOONS.length} |`);
L(`| attunements | ${ATTUNE.length} |`);
L(`| threat tiers | ${THREATS.length} |`);
L(`| lore fragments | ${LORE.frag.length} |`);
console.log(out.join('\n'));
